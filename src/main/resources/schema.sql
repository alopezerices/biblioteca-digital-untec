CREATE TABLE IF NOT EXISTS usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
 password_hash VARCHAR(200) NOT NULL, rol VARCHAR(20) NOT NULL CHECK(rol IN ('ADMIN','ESTUDIANTE')));
CREATE TABLE IF NOT EXISTS libro (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(160) NOT NULL, autor VARCHAR(120) NOT NULL,
 isbn VARCHAR(30) NOT NULL UNIQUE, ejemplares INT NOT NULL CHECK(ejemplares>=1 AND ejemplares<=1000));
CREATE TABLE IF NOT EXISTS prestamo (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 libro_id BIGINT NOT NULL REFERENCES libro(id),
 fecha DATE NOT NULL, vence DATE NOT NULL, devolucion DATE,
 CHECK(vence>=fecha), CHECK(devolucion IS NULL OR devolucion>=fecha));
CREATE INDEX IF NOT EXISTS ix_prestamo_libro ON prestamo(libro_id,devolucion);
CREATE INDEX IF NOT EXISTS ix_prestamo_usuario ON prestamo(usuario_id,fecha);
